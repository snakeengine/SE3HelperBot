#!/usr/bin/env bash
set -euo pipefail

# ====== ????? ???? ???????? ?????? ??????? ======
mkdir -p /data
rm -f /data/.feature_flags.lock /data/maintenance /data/.maintenance || true

# ====== ???? /data/.env ?????? ????? .env ======
touch /data/.env
if [ -f ./.env ] && [ ! -s /data/.env ]; then cp ./.env /data/.env; fi
ln -sf /data/.env .env || true

# ====== ???? MAINTENANCE=0 ???? /data/.env ======
if grep -q "^MAINTENANCE=" /data/.env 2>/dev/null; then
  sed -i "s/^MAINTENANCE=.*/MAINTENANCE=0/" /data/.env || true
else
  printf "\nMAINTENANCE=0\n" >> /data/.env
fi

# ====== ???? BOT_TOKEN ?????? ?? ???? Railway ??? /data/.env (?? ?????) ======
if [ -n "${BOT_TOKEN:-}" ]; then
  sed -i "/^BOT_TOKEN=/d" /data/.env || true
  printf "BOT_TOKEN=%s\n" "$BOT_TOKEN" >> /data/.env
fi

# ====== ???? ?? ??????? .env ??? ???? ??????? ======
set -a
. ./.env
set +a

# ====== ??? ?????? (???? ??? ?????? ????) ======
echo "[BOOT] MAINTENANCE=${MAINTENANCE:-unset}"
echo "[BOOT] BOT_TOKEN present? $([ -n "${BOT_TOKEN:-}" ] && echo yes || echo no)"

# ====== ???? ????? ======
exec /app/.venv/bin/python bot.py || exec python3 bot.py